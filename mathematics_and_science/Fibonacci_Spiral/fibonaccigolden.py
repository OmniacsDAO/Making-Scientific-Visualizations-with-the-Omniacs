    # PART 6 — THE MATHEMATICS
    # ══════════════════════════════════════════════════════════════════════
    def part6_math(self):
        self.set_camera_orientation(phi=0, theta=-PI / 2)

        hdr = Text("STEP 6 — The Mathematics of φ",
                   font_size=30, color=C_CYAN, weight=BOLD).to_corner(UL)
        self.play(FadeIn(hdr))

        eqs = [
            (r"\varphi^2 = \varphi + 1",
             "φ is the only number equal to\nits own square minus 1",
             C_GOLD),
            (r"\varphi = 1 + \cfrac{1}{1+\cfrac{1}{1+\cfrac{1}{\ddots}}}",
             "Infinite continued fraction\n— simplest possible",
             C_CYAN),
            (r"\varphi = \sqrt{1+\sqrt{1+\sqrt{1+\cdots}}}",
             "Infinite nested radicals",
             C_GREEN),
            (r"\lim_{n\to\infty}\frac{F_{n+1}}{F_n} = \varphi",
             "Fibonacci ratio converges to φ",
             C_ORANGE),
        ]

        rows = VGroup()
        for latex, desc, col in eqs:
            eq_mob = MathTex(latex, font_size=34, color=col)
            desc_mob = Text(desc, font_size=17, color=C_DIM)
            sep = DashedLine(LEFT * 0.01, RIGHT * 0.01,
                             stroke_width=0)  # invisible spacer
            row = VGroup(eq_mob, desc_mob).arrange(RIGHT, buff=0.55,
                                                    aligned_edge=UP)
            bg = RoundedRectangle(
                corner_radius=0.14,
                width=row.width + 0.5,
                height=row.height + 0.32,
                fill_color=col, fill_opacity=0.07,
                stroke_color=col, stroke_width=1.2,
            )
            bg.move_to(row)
            rows.add(VGroup(bg, row))

        rows.arrange(DOWN, buff=0.30, aligned_edge=LEFT).center().shift(DOWN * 0.3)

        for r in rows:
            self.play(FadeIn(r, shift=RIGHT * 0.15), run_time=0.60)

        self.wait(2.8)
        self.play(FadeOut(VGroup(hdr, rows)))

