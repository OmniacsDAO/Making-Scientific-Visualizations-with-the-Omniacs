    # PART 5 — 3-D GOLDEN SPIRAL
    # ══════════════════════════════════════════════════════════════════════
    def part5_spiral_3d(self):
        self.set_camera_orientation(phi=65 * DEGREES, theta=-50 * DEGREES)

        hdr = Text("STEP 5 — Golden Spiral in 3D",
                   font_size=28, color=C_CYAN, weight=BOLD)
        hdr.to_corner(UL)
        self.add_fixed_in_frame_mobjects(hdr)
        self.play(FadeIn(hdr))

        axes = ThreeDAxes(
            x_range=[-4, 4, 1], y_range=[-4, 4, 1], z_range=[-3, 3, 1],
            x_length=7, y_length=7, z_length=5,
            axis_config={"color": C_DIM, "stroke_opacity": 0.4},
        )
        self.play(Create(axes), run_time=0.8)

        # True logarithmic golden spiral lifted into 3D helix
        # r(θ) = e^(θ * ln(φ) / (π/2))  — grows by φ each quarter turn
        b = np.log(PHI) / (PI / 2)

        spiral1 = ParametricFunction(
            lambda t: np.array([
                np.exp(b * t) * np.cos(t) * 0.55,
                np.exp(b * t) * np.sin(t) * 0.55,
                t * 0.18,
            ]),
            t_range=[-2 * PI, 3.5 * PI, 0.04],
            stroke_width=3.5,
        )
        spiral1.set_color_by_gradient(C_PURPLE, C_CYAN, C_GOLD)

        spiral2 = ParametricFunction(
            lambda t: np.array([
                np.exp(b * t) * np.cos(t) * 0.55,
                np.exp(b * t) * np.sin(t) * 0.55,
                -t * 0.18,
            ]),
            t_range=[-2 * PI, 3.5 * PI, 0.04],
            stroke_width=3.5,
        )
        spiral2.set_color_by_gradient(C_PINK, C_ORANGE, C_GREEN)

        dot = Dot(radius=0.10, color=C_GOLD)

        self.play(Create(spiral1, run_time=3.5), rate_func=linear)
        self.play(Create(spiral2, run_time=3.5), rate_func=linear)

        note = Text("r grows by φ each quarter turn", font_size=22, color=C_GOLD)
        note.to_edge(DOWN, buff=0.45)
        self.add_fixed_in_frame_mobjects(note)
        self.play(Write(note))

        self.begin_ambient_camera_rotation(rate=0.22)
        self.wait(2.8)
        self.move_camera(phi=30 * DEGREES, theta=120 * DEGREES, run_time=2.5)
        self.move_camera(phi=70 * DEGREES, theta=240 * DEGREES, run_time=2.5)
        self.stop_ambient_camera_rotation()

        self.play(FadeOut(VGroup(axes, spiral1, spiral2, note, hdr)))

